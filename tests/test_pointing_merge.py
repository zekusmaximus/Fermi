def _receipt(script, **over):
    summary = over.pop("summary")
    rec = {
        "kind": script.KIND,
        "data_tier": "reproduced_archive",
        "status": "ok",
        "code_git_sha": "c" * 40,
        "cache": {"code_git_shas": ["c" * 40]},
        "pointing_coverage": {"n_pointings": 692, "n_pointings_completed": 692},
        "locked_inputs": {"primary_catalog_sha256": script.LOCKED_CATALOG_SHA256},
        "summary": summary,
    }
    rec.update(over)
    return rec


@pytest.mark.parametrize(
    ("label", "over", "message"),
    [
        ("dirty", {"code_git_sha": "dirty"}, "code_git_sha 'dirty' is not a clean commit"),
        ("unknown", {"code_git_sha": "unknown"}, "is not a clean commit"),
        ("dirty_cache", {"cache": {"code_git_shas": ["c" * 40, "dirty"]}}, "non-clean tree"),
        (
            "incomplete",
            {"pointing_coverage": {"n_pointings": 692, "n_pointings_completed": 691}},
            "incomplete pointing coverage: 691 of 692 pointings",
        ),
        ("status", {"status": "incomplete"}, "receipt status 'incomplete'"),
        ("tier", {"data_tier": "synthetic_proxy"}, "not a reproduced_archive"),
        ("catalog", {"locked_inputs": {"primary_catalog_sha256": "0" * 64}}, "locked bl_692"),
        ("no_summary", {"summary": None}, "no summary"),
    ],
)
def test_promote_refuses_dirty_incomplete_or_mislabelled_receipts(
    script, synthetic, tmp_path, capsys, label, over, message
):
    """Negative-path receipts only: each is fabricated in tmp_path to be REFUSED."""
    path, out = tmp_path / f"{label}.json", tmp_path / "promoted.json"
    path.write_text(json.dumps(_receipt(script, **{"summary": synthetic.doc, **over})), "utf-8")
    before = _project_artifact_state()
    assert script.main(["--promote-from", str(path), "--out-file", str(out)]) == 1
    err = capsys.readouterr().err
    assert "Refusing to promote" in err and message in err
    assert not out.exists() and _project_artifact_state() == before


def test_promote_refuses_synthetic_and_oversized_output(script, synthetic, tmp_path, capsys):
    out = tmp_path / "promoted.json"
    # 1. Every receipt-level gate passes, but the summary is a synthetic rehearsal.
    path = tmp_path / "synthetic.json"
    path.write_text(json.dumps(_receipt(script, summary=synthetic.doc)), "utf-8")
    assert script.promote(path, out) == 1
    assert "synthetic rehearsal output can never be promoted" in capsys.readouterr().err
    # 2. A summary at or above 5 MB is refused whatever else is true.
    padded = {**synthetic.doc, "description": "x" * (5 * 1024 * 1024)}
    path = tmp_path / "oversized.json"
    path.write_text(json.dumps(_receipt(script, summary=padded)), "utf-8")
    assert script.promote(path, out) == 1
    assert "oversized output" in capsys.readouterr().err and not out.exists()
    with pytest.raises(ProvenanceError, match="5242880"):
        write_background_summary(padded, tmp_path / "direct.json")
    assert not (tmp_path / "direct.json").exists()


