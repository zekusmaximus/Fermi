def sightings(survey_id, role, rows) -> SightingTable:
    """rows: (name, gaia_id | None, ra_deg, dec_deg, distance_pc, pointing_index, theta_arcmin)."""
    names = np.array([r[0] for r in rows], dtype=object)
    ids = np.array([MISSING_GAIA_ID if r[1] is None else r[1] for r in rows], np.int64)
    pointing = np.array([r[5] for r in rows], np.int64)
    theta = np.array([r[6] for r in rows], float)
    return SightingTable(
        survey_id=survey_id,
        role=role,
        sha256=sightings_sha256(names, ids, pointing, theta),
        names=names,
        gaia_dr3_source_id=ids,
        ra_deg=np.array([r[2] for r in rows], float),
        dec_deg=np.array([r[3] for r in rows], float),
        distance=np.array([r[4] for r in rows], float) * u.pc,
        pointing_index=pointing,
        theta=theta * u.arcmin,
    )


