def test_union_of_bl692_and_synthetic_background_has_zero_duplicate_gaia_ids(synthetic, script):
    m, p = synthetic.merged, synthetic.merged.provenance
    kept = [script.attach_distances(f)[0] for f in synthetic.frames.values()]
    n_sightings = sum(len(k) for k in kept)
    own = {int(x) for k in kept for x in k.loc[k["parallax_over_error"] == 100.0, "source_id"]}
    stars = {int(x) for k in kept for x in k["source_id"]} - own

    win_ids = m.gaia_dr3_source_id[m.winner]
    win_ids = win_ids[win_ids != MISSING_GAIA_ID]
    assert len(np.unique(win_ids)) == len(win_ids) and m.duplicate_gaia_ids().size == 0
    assert p.n_duplicate_gaia_ids_post_merge == 0
    # Exact counts, recounted independently of the kernel.
    assert p.policy == UNION_TARGETS_BY_POINTING and p.pointing_group_id == GROUP
    assert p.input_surveys == [PARENT, EXT]
    assert p.input_sha256s[0] == synthetic.parent.catalog_sha256
    assert p.n_raw_targets == 692 + n_sightings
    assert p.n_raw_by_survey == {PARENT: 692, EXT: n_sightings}
    assert p.n_merged_by_role == {"primary": 692, "background": len(stars)}
    assert p.n_merged_targets == 692 + len(stars) == len(m)
    assert p.n_raw_targets - p.n_merged_targets == p.n_dedup_gaia_id + p.n_dedup_angular_fallback
    # 170 primaries carry no Gaia id: each absorbs its own sighting through the 3 arcsec
    # fallback (after J2000 back-propagation); the 522 with an id match exactly.
    n_no_id = int(np.sum(synthetic.primary.gaia_dr3_source_id == MISSING_GAIA_ID))
    assert (n_no_id, 692 - n_no_id) == (170, 522)
    assert p.n_dedup_angular_fallback == n_no_id
    assert p.n_background_absorbed_by_primary >= 692 and p.n_multi_beam_resolved > 0
    # Every primary survives, on-axis, in catalog order; GJ 702A / B (identical published
    # coordinates) are never merged with each other.
    prim = m.winner[m.winner_role == "primary"]
    assert np.array_equal(m.names[prim], synthetic.primary.names)
    assert np.all(m.theta[prim].value == 0.0) and p.n_angular_links_refused >= 1
    # No primary star is left in a shell: binning happens after the merge.
    doc = synthetic.doc
    assert doc["shells"]["n_stars"] == len(stars) == sum(doc["shells"]["count"])
    assert doc["dedup_audit"]["n_duplicate_gaia_ids_vs_primary"] == 0
    assert len(doc["validation_sample"]["primary_matched"]) == p.n_background_absorbed_by_primary
    BackgroundSummaryFile.model_validate(doc)


