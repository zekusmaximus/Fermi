    for path in (root / "data" / "surveys").glob("*.yaml"):
        if yaml.safe_load(path.read_text("utf-8")).get("parent_pointing_survey_id"):
            path.unlink()
    (root / BACKGROUND_SUMMARY_PATH).unlink(missing_ok=True)


