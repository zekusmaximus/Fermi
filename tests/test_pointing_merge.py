def test_default_policy_holds_a_declared_extension_out_and_equals_single_survey(
    plain_graph, merged_graph
):
    """Under reject_duplicate_pointing_group the extension is reported, not merged, and the
    run is numerically the single-survey run (same results_sha256)."""
    plain = run_comparison(plain_graph, _cfg(), list(PAIR))
    held = run_comparison(merged_graph, _cfg(), list(PAIR))
    assert results_digest(held) == results_digest(plain)
    assert held["pointing_merge_policy"] == REJECT_DUPLICATE_POINTING_GROUP
    assert held["merge_provenance"] is None
    (h,) = held["held_out_extension_surveys"]
    assert h["survey_id"] == EXT and h["parent_pointing_survey_id"] == PARENT
    assert [s["id"] for s in held["active_surveys"]] == [PARENT]
    assert "background" not in held["results"]["hypotheses"][PAIR[0]]["radio"]
    assert plain["held_out_extension_surveys"] == [] and plain["merge_provenance"] is None


def test_union_policy_merges_the_extension_and_records_merge_provenance(merged_graph, synthetic):
    plain = run_comparison(merged_graph, _cfg(), list(PAIR))
    rec = run_comparison(
        merged_graph, _cfg(pointing_merge_policy=UNION_TARGETS_BY_POINTING), list(PAIR)
    )
    assert rec["receipt_schema_version"] == RECEIPT_SCHEMA_VERSION == 5
    assert rec["pointing_merge_policy"] == UNION_TARGETS_BY_POINTING
    assert rec["config"]["pointing_merge_policy"] == UNION_TARGETS_BY_POINTING
    mp = MergeProvenance.model_validate(rec["merge_provenance"])
    assert mp == synthetic.merged.provenance and rec["held_out_extension_surveys"] == []
    assert [s["id"] for s in rec["active_surveys"]] == [PARENT, EXT]
    assert rec["active_surveys"][1]["merged_into"] == PARENT
    assert "synthetic_proxy" in rec["data_tiers_used"]
    n_bg = synthetic.doc["shells"]["n_stars"]
    for hid in PAIR:
        r, r0 = rec["results"]["hypotheses"][hid], plain["results"]["hypotheses"][hid]
        bg = r["radio"]["background"]
        assert bg["n_stars"] == n_bg and r["radio"]["n_targets_merged"] == 692 + n_bg
        assert bg["data_tier"] == "synthetic_proxy" and "FKG" in bg["evaluation"]
        assert "LOWER bound" in bg["spatial_correlation_assumption"]
        # Primaries keep the exact MC term; the shells multiply onto it.
        base = r0["components"]["radio"]["log10_p_data_given_h"]
        assert bg["log10_p_zero_primary_mc"] == base
        assert r["components"]["radio"]["log10_p_data_given_h"] == pytest.approx(
            base + bg["log10_p_zero_independent_fkg_lower"], abs=1e-15
        )
        assert bg["log10_p_zero_independent_fkg_lower"] < 0 < bg["expected_detections"]
        # FKG product <= Frechet upper bound; Markov lower bound <= FKG product.
        assert bg["p_zero_markov_lower"] <= bg["p_zero_independent_fkg_lower"] + 1e-15
        assert bg["p_zero_independent_fkg_lower"] <= bg["p_zero_frechet_upper"]
