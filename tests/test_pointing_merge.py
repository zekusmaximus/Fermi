def test_tampered_background_summary_is_rejected(merged_root, synthetic, tmp_path):
    parent_doc = yaml.safe_load((ROOT / "data/surveys" / f"{PARENT}.yaml").read_text("utf-8"))

    def root_with(doc, repin=True):
        root = tmp_path / f"case{len(list(tmp_path.iterdir()))}"
        shutil.copytree(merged_root / "data", root / "data")
        if repin:
            _write_extension(root, doc, parent_doc)
        else:
            write_background_summary(doc, root / BACKGROUND_SUMMARY_PATH)
        g = load_factor_graph(root)
        return lambda: load_background_summary(g.surveys[EXT], g.surveys[PARENT], root)

    doc = synthetic.doc
    from fermi_desk.registry import seal_background_summary as seal

    with pytest.raises(ProvenanceError, match="sha256"):  # bytes changed, pin not updated
        root_with({**doc, "description": doc["description"] + " "}, repin=False)()
    with pytest.raises(ProvenanceError, match="content_sha256"):  # re-pinned but not re-sealed
        root_with({**doc, "description": "edited"})()
    # Re-pinned AND re-sealed tampering is caught by the offline recomputation.
    star = dict(doc["validation_sample"]["background"][0])
    for field, value, message in (
        ("eirp_min_w", star["eirp_min_w"] * 0.5, "EIRP_min"),
        ("theta_arcmin", star["theta_arcmin"] * 0.5 + 0.01, "theta"),
    ):
        sample = [{**star, field: value}, *doc["validation_sample"]["background"][1:]]
        bad = seal({**doc, "validation_sample": {**doc["validation_sample"], "background": sample}})
        with pytest.raises(ProvenanceError, match=message):
            root_with(bad)()
    wrong_catalog = seal({**doc, "primary_catalog_sha256": "0" * 64})
    with pytest.raises(ProvenanceError):
        root_with(wrong_catalog)()
    cells = {**doc["shells"], "count": [doc["shells"]["count"][0] + 1, *doc["shells"]["count"][1:]]}
    with pytest.raises((ProvenanceError, SchemaValidationError)):
        root_with(seal({**doc, "shells": cells}))()


