def test_keep_first_is_refused_everywhere_with_an_explicit_reason(graph):
    bl = graph.surveys[PARENT]
    dup = bl.model_copy(update={"id": "bl_reanalysis"})
    calls = [
        lambda: validate_pointing_merge_policy("keep_first"),
        lambda: resolve_pointing_groups([bl, dup], "keep_first"),
        lambda: check_pointing_groups([bl, dup], {GROUP: "keep_first"}),  # pre-v0.2.1 call form
        lambda: check_pointing_groups([bl], "keep_first"),  # refused even with nothing to merge
        lambda: RunConfig(
            geometry="thin_disk_2d",
            radio_mode="flat_probability",
            seed=1,
            pointing_merge_policy="keep_first",
        ),
        lambda: Survey.model_validate({**bl.model_dump(), "pointing_merge_policy": "keep_first"}),
    ]
    for call in calls:
        with pytest.raises(MergePolicyError) as err:
            call()
        assert "load order" in str(err.value) and str(err.value) == KEEP_FIRST_FORBIDDEN_REASON
    assert issubclass(MergePolicyError, DoubleCountingError)
    with pytest.raises(MergePolicyError, match="unknown pointing merge policy"):
        validate_pointing_merge_policy("keep_last")


