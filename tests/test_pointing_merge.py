def test_audit_pointing_overlap_recounts_a_star_level_merge(graph, synthetic):
    ok = audit_pointing_overlap(graph, merged=synthetic.merged)
    rc = ok.details["star_level_recount"]
    assert ok.status == "pass" and ok.details["keep_first_refused_by_registry"]
    assert rc["n_duplicate_gaia_ids_post_merge"] == 0 and rc["n_unmerged_angular_collisions"] == 0
    assert rc["n_kept_sightings_not_minimum_offset"] == 0 and rc["provenance_counts_consistent"]
    assert rc["n_merged_targets_recounted"] == len(synthetic.merged)
    # Corrupt the merge: resurrect an absorbed background sighting as its own "star".
    m = synthetic.merged
    absorbed = next(
        int(r)
        for r in m.absorbed_rows()
        if m.gaia_dr3_source_id[r] != MISSING_GAIA_ID
        and m.gaia_dr3_source_id[m.winner[m.cluster[r]]] == m.gaia_dr3_source_id[r]
    )
    cluster = m.cluster.copy()
    cluster[absorbed] = len(m.winner)
    broken = dataclasses.replace(m, winner=np.append(m.winner, absorbed), cluster=cluster)
    bad = audit_pointing_overlap(graph, merged=broken)
    assert (bad.status, bad.severity) == ("fail", "critical")
    assert bad.details["star_level_recount"]["n_duplicate_gaia_ids_post_merge"] == 1
    assert "duplicated Gaia ids" in bad.summary


