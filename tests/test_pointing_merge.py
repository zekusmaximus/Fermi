def test_default_policy_rejects_unconfigured_duplicate_pointing_groups(plain_graph):
    graph = plain_graph
    bl = graph.surveys[PARENT]
    dup = bl.model_copy(update={"id": "bl_reanalysis"})
    for policy in (REJECT_DUPLICATE_POINTING_GROUP, UNION_TARGETS_BY_POINTING):
        # Unrelated surveys on one pointing group are refused under EVERY policy: union needs
        # a declared parent-pointing relationship, it is not a licence to merge anything.
        with pytest.raises(DoubleCountingError, match="without a declared compatible"):
            resolve_pointing_groups([bl, dup], policy)
    res = resolve_pointing_groups(list(graph.surveys.values()))
    assert res.policy == REJECT_DUPLICATE_POINTING_GROUP and not res.merges and not res.held_out
    assert [s.id for s in res.active] == list(graph.surveys)


