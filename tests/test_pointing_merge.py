def test_beam_response_and_off_axis_eirp_invariants(bl_targets):
    assert 8.4 * u.arcmin == radio.GBT_LBAND_BEAM_FWHM
    assert radio.beam_response(0.0 * u.arcmin) == 1.0
    assert radio.beam_response(4.2 * u.arcmin) == 0.5
    assert radio.beam_response(8.4 * u.arcmin) == 0.0625  # 2^-4
    # The Gaussian form exp(-4 ln2 (theta / FWHM)^2), in any angular unit.
    theta = np.linspace(0.0, 12.0, 241) * u.arcmin
    gauss = np.exp(-4.0 * np.log(2.0) * (theta / (8.4 * u.arcmin)).to_value(1) ** 2)
    assert np.allclose(radio.beam_response(theta), gauss, rtol=1e-14, atol=0)
    assert np.allclose(radio.beam_response(theta.to(u.deg)), gauss, rtol=1e-12, atol=0)
    assert radio.beam_response(3.0 * u.arcmin, 6.0 * u.arcmin) == 0.5  # parameterised FWHM

    d = bl_targets.distance
    on_axis = radio.min_detectable_eirp(d, F_MIN)
    off0 = radio.min_detectable_eirp_off_axis(d, np.zeros(len(d)) * u.arcmin, F_MIN)
    assert off0.unit == u.W and np.array_equal(off0.value, on_axis.value)  # byte-identical
    half = radio.min_detectable_eirp_off_axis(d, 4.2 * u.arcmin, F_MIN)
    assert np.array_equal(half.value, 2.0 * on_axis.value)  # exactly doubled at FWHM / 2
    # Strictly increasing in theta at fixed distance, in watts.
    e = radio.min_detectable_eirp_off_axis(100.0 * u.pc, theta, F_MIN)
    assert e.unit == u.W and np.all(np.diff(e.value) > 0)
    assert e[0] == radio.min_detectable_eirp(100.0 * u.pc, F_MIN)
    for bad in (4.2, 4.2 * u.pc):
        with pytest.raises(UnitValidationError):
            radio.beam_response(bad)
    with pytest.raises(UnitValidationError):
        radio.min_detectable_eirp_off_axis(100.0, 1.0 * u.arcmin, F_MIN)
    with pytest.raises(ValueError):
        radio.beam_response(-1.0 * u.arcmin)


