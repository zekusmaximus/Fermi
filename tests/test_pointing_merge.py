def test_angular_fallback_only_applies_when_a_gaia_id_is_missing():
    ra, dec = 150.0, 20.0
    primary = sightings("prim", "primary", [("T1", None, ra, dec, 10.0, 0, 0.0)])
    background = sightings(
        "bg",
        "background",
        [
            ("X1", None, ra, dec + 2.0 * ARCSEC, 10.0, 0, 2.0 / 60.0),  # < 3": same star as T1
            ("X2", None, ra, dec + 8.0 * ARCSEC, 300.0, 0, 8.0 / 60.0),  # > 3" from both: distinct
            ("X3", 111, ra, dec + 60.0 * ARCSEC, 500.0, 0, 1.0),
            ("X4", 111, ra, dec + 60.0 * ARCSEC, 500.0, 1, 2.0),  # same Gaia id, other beam
            ("X5", 555, ra, dec + 120.0 * ARCSEC, 700.0, 0, 2.0),
            (
                "X6",
                666,
                ra,
                dec + 121.0 * ARCSEC,
                900.0,
                0,
                2.0 + 1 / 60,
            ),  # 1" from X5, both have ids
        ],
    )
    m = union_targets_by_pointing(GROUP, [primary, background])
    p = m.provenance
    assert [str(x) for x in m.names[m.winner]] == ["T1", "X2", "X3", "X5", "X6"]
    assert (p.n_dedup_angular_fallback, p.n_dedup_gaia_id) == (1, 1)
    assert p.n_raw_targets == 7 and p.n_merged_targets == 5
    assert m.source_surveys(0) == ("prim", "bg")  # merged source provenance of T1
    assert m.source_surveys(1) == ("bg",)
    # A wider fallback radius would also swallow X2: the 3 arcsec default is what keeps it.
    wide = union_targets_by_pointing(GROUP, [primary, background], angular_fallback=7 * u.arcsec)
    assert wide.provenance.n_dedup_angular_fallback == 2
    with pytest.raises(UnitValidationError):
        union_targets_by_pointing(GROUP, [primary, background], angular_fallback=3.0)


def test_angular_fallback_never_joins_two_gaia_ids_or_two_published_primaries():
    ra, dec = 40.0, -10.0
    # Two published targets at identical coordinates (cf. GJ 702A / GJ 702B), neither with an id.
    primary = sightings(
        "prim", "primary", [("A", None, ra, dec, 5.0, 0, 0.0), ("B", None, ra, dec, 5.0, 1, 0.0)]
    )
    background = sightings(
        "bg",
        "background",
        [
            ("G1", 1, ra, dec + 0.5 * ARCSEC, 5.0, 0, 0.5 / 60),
            ("G2", 2, ra, dec + 1.0 * ARCSEC, 5.0, 0, 1.0 / 60),
        ],
    )
    m = union_targets_by_pointing(GROUP, [primary, background])
    assert [str(x) for x in m.names[m.winner]] == ["A", "B"]  # each absorbs one Gaia star
    assert m.provenance.n_dedup_angular_fallback == 2 and m.provenance.n_angular_links_refused >= 1
    clusters = {str(m.names[r]): int(m.cluster[r]) for r in range(len(m.cluster))}
    assert clusters["A"] != clusters["B"] and clusters["G1"] != clusters["G2"]
    assert audit_pointing_overlap(load_factor_graph(ROOT), merged=m).status == "pass"


def test_multi_beam_collision_keeps_minimum_offset_and_primary_wins():
    primary = sightings(
        "prim",
        "primary",
        [("P42", 42, 10.0, 10.0, 20.0, 0, 0.0), ("P43", 43, 10.05, 10.0, 30.0, 1, 0.0)],
    )
    background = sightings(
        "bg",
        "background",
        [
            ("P42 seen from beam 1", 42, 10.0, 10.0, 20.0, 1, 2.8),  # primary also off-axis
            ("S77 beam 0", 77, 10.02, 10.0, 400.0, 0, 2.8),
            ("S77 beam 1", 77, 10.02, 10.0, 400.0, 1, 1.1),  # same star, closer to beam 1
            ("S88", 88, 10.01, 10.0, 800.0, 0, 0.0),  # exactly on-axis background: still background
        ],
    )
    m = union_targets_by_pointing(GROUP, [primary, background])
    kept = {str(m.names[w]): w for w in m.winner}
    assert set(kept) == {"P42", "P43", "S77 beam 1", "S88"}
    assert m.theta[kept["P42"]].value == 0.0  # on-axis primary beats its 2.8' sighting
    assert m.theta[kept["S77 beam 1"]].to_value(u.arcmin) == 1.1
    assert m.pointing_index[kept["S77 beam 1"]] == 1
    assert m.provenance.n_multi_beam_resolved == 2 and m.provenance.n_dedup_gaia_id == 2
    assert m.provenance.n_background_absorbed_by_primary == 1
    # theta_min is the lowest EIRP_min sighting, in watts.
    e = radio.min_detectable_eirp_off_axis(400 * u.pc, [2.8, 1.1] * u.arcmin, F_MIN)
    assert e.unit == u.W and e[1] < e[0]
    # Input order of the two background sightings must not matter.
    flipped = dataclasses.replace(
        background,
        **{
            f.name: getattr(background, f.name)[[0, 2, 1, 3]]
            for f in dataclasses.fields(background)
            if f.name not in ("survey_id", "role", "sha256")
        },
    )
    m2 = union_targets_by_pointing(GROUP, [primary, flipped])
    assert m2.theta[m2.winner].value.tolist() == m.theta[m.winner].value.tolist()


